	fmt.Fprintf(&b, "func New%sRepository(db dbgen.DBTX) *%sRepository { return &%sRepository{queries: dbgen.New(db)} }\n", n, n, n)
	fmt.Fprintf(&b, "func (r *%sRepository) Create(ctx context.Context, value domain.%s) (domain.%s, error) { created, err := r.queries.Create%s(ctx, toCreate%sParams(value)); if err != nil { return domain.%s{}, fmt.Errorf(\"insert %s: %%w\", err) }; return toDomain%s(created), nil }\n", n, n, n, n, n, n, d.Name, n)
