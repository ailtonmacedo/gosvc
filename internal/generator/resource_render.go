func openAPIYAMLType(t string, indent int) string {
	pad := strings.Repeat(" ", indent)
	switch t {
	case "int64":
		return pad + "type: integer\n" + pad + "format: int64\n"
	case "bool":
		return pad + "type: boolean\n"
	case "datetime":
		return pad + "type: string\n" + pad + "format: date-time\n"
	case "uuid":
		return pad + "type: string\n" + pad + "format: uuid\n"
	default:
		return pad + "type: string\n"
	}
}
func goType(t string) string {
	switch t {
	case "uuid":
		return "uuid.UUID"
	case "int64":
		return "int64"
	case "bool":
		return "bool"
	case "datetime":
		return "time.Time"
	default:
		return "string"
	}
}

func dbGoType(t string) string {
	if t == "datetime" {
		return "pgtype.Timestamptz"
	}
	return goType(t)
}

func hasFieldType(d resource.Definition, fieldType string) bool {
	for _, field := range d.Fields {
		if field.Type == fieldType {
			return true
		}
	}
	return false
}

func openAPIGoType(t string) string { return goType(t) }
func sqlType(f resource.Field, primary bool) string {
	if f.Name == "id" && primary {
		if f.Type == "int64" {
			return "BIGSERIAL PRIMARY KEY"
		}
		if f.Type == "uuid" {
			return "UUID PRIMARY KEY DEFAULT gen_random_uuid()"
		}
		return "TEXT PRIMARY KEY"
	}
	switch f.Type {
	case "int64":
		return "BIGINT NOT NULL"
	case "bool":
		return "BOOLEAN NOT NULL"
	case "datetime":
		return "TIMESTAMPTZ NOT NULL"
	case "uuid":
		return "UUID NOT NULL"
	default:
		return "TEXT NOT NULL"
	}
}
func createFields(d resource.Definition) []resource.Field {
	r := []resource.Field{}
	for _, f := range d.Fields {
		if f.Name != "id" {
			r = append(r, f)
		}
	}
	return r
}
func columnNames(fields []resource.Field) []string {
	r := make([]string, len(fields))
	for i, f := range fields {
		r[i] = f.Name
	}
	return r
}
func scanArgs(d resource.Definition, v string) string {
	r := []string{}
	for _, f := range d.Fields {
		r = append(r, "&"+v+"."+exported(f.Name))
	}
	r = append(r, "&"+v+".CreatedAt", "&"+v+".UpdatedAt")
	return strings.Join(r, ",")
}
func exported(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool { return r == '_' || r == '-' })
	for i, part := range parts {
		switch strings.ToLower(part) {
		case "id":
			parts[i] = "ID"
		case "url":
			parts[i] = "URL"
		case "api":
			parts[i] = "API"
		default:
			runes := []rune(part)
			if len(runes) > 0 {
				runes[0] = unicode.ToUpper(runes[0])
			}
			parts[i] = string(runes)
		}
	}
	return strings.Join(parts, "")
}

