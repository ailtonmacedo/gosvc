func buildRepositoryMappers(d resource.Definition) string {
	n := exported(d.Name)
	var b strings.Builder
	fmt.Fprintf(&b, "\nfunc toDomain%s(v dbgen.%s) domain.%s{return domain.%s{", n, n, n, n)
	for _, f := range d.Fields {
		if f.Type == "datetime" {
			fmt.Fprintf(&b, "%s:timeFromDB(v.%s),", exported(f.Name), exported(f.Name))
			continue
		}
		fmt.Fprintf(&b, "%s:v.%s,", exported(f.Name), exported(f.Name))
	}
	b.WriteString("CreatedAt:timeFromDB(v.CreatedAt),UpdatedAt:timeFromDB(v.UpdatedAt)}}\n")
	fmt.Fprintf(&b, "func toCreate%sParams(v domain.%s) dbgen.Create%sParams{return dbgen.Create%sParams{", n, n, n, n)
	for _, f := range createFields(d) {
		if f.Type == "datetime" {
			fmt.Fprintf(&b, "%s:timeToDB(v.%s),", exported(f.Name), exported(f.Name))
			continue
		}
		fmt.Fprintf(&b, "%s:v.%s,", exported(f.Name), exported(f.Name))
	}
	b.WriteString("}}\n")
	fmt.Fprintf(&b, "func toUpdate%sParams(v domain.%s) dbgen.Update%sParams{return dbgen.Update%sParams{", n, n, n, n)
	for _, f := range d.Fields {
		if f.Type == "datetime" {
			fmt.Fprintf(&b, "%s:timeToDB(v.%s),", exported(f.Name), exported(f.Name))
			continue
		}
		fmt.Fprintf(&b, "%s:v.%s,", exported(f.Name), exported(f.Name))
	}
	b.WriteString("}}\n")
	return b.String()
}

func buildDBGen(d resource.Definition) string {
	n := exported(d.Name)
	var b strings.Builder
	b.WriteString("// Code generated by sqlc-compatible gosvc snapshot. DO NOT EDIT.\npackage dbgen\n\nimport (\n\t\"context\"\n\n\t\"github.com/jackc/pgx/v5/pgtype\"\n")
	if hasFieldType(d, "uuid") {
		b.WriteString("\n\t\"github.com/google/uuid\"\n")
	}
	b.WriteString(")\n")
	fmt.Fprintf(&b, "type %s struct{", n)
	for _, f := range d.Fields {
		fmt.Fprintf(&b, "%s %s;", exported(f.Name), dbGoType(f.Type))
	}
	b.WriteString("CreatedAt pgtype.Timestamptz;UpdatedAt pgtype.Timestamptz}\n")
	fmt.Fprintf(&b, "type Create%sParams struct{", n)
	for _, f := range createFields(d) {
		fmt.Fprintf(&b, "%s %s;", exported(f.Name), dbGoType(f.Type))
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "type Update%sParams struct{", n)
	for _, f := range d.Fields {
		fmt.Fprintf(&b, "%s %s;", exported(f.Name), dbGoType(f.Type))
	}
	b.WriteString("}\n")
	fmt.Fprintf(&b, "type List%sParams struct{Limit int32;Offset int32}\n", n)
	cols := columnNames(d.Fields)
	create := createFields(d)
	ccols := columnNames(create)
	placeholders := make([]string, len(create))
	for i := range placeholders {
		placeholders[i] = fmt.Sprintf("$%d", i+1)
	}
	fmt.Fprintf(&b, "const create%s=%q\n", n, fmt.Sprintf("INSERT INTO %s (%s) VALUES (%s) RETURNING %s, created_at, updated_at", d.Plural, strings.Join(ccols, ", "), strings.Join(placeholders, ", "), strings.Join(cols, ", ")))
	fmt.Fprintf(&b, "func(q *Queries)Create%s(ctx context.Context,arg Create%sParams)(%s,error){row:=q.db.QueryRow(ctx,create%s", n, n, n, n)
	for _, f := range create {
		fmt.Fprintf(&b, ",arg.%s", exported(f.Name))
	}
	fmt.Fprintf(&b, ");var v %s;err:=row.Scan(%s);return v,err}\n", n, scanArgs(d, "v"))
	fmt.Fprintf(&b, "func(q *Queries)Get%s(ctx context.Context,id %s)(%s,error){row:=q.db.QueryRow(ctx,%q,id);var v %s;err:=row.Scan(%s);return v,err}\n", n, goType(d.ID().Type), n, fmt.Sprintf("SELECT %s, created_at, updated_at FROM %s WHERE id = $1", strings.Join(cols, ", "), d.Plural), n, scanArgs(d, "v"))
	fmt.Fprintf(&b, "func(q *Queries)List%s(ctx context.Context,arg List%sParams)([]%s,error){rows,err:=q.db.Query(ctx,%q,arg.Limit,arg.Offset);if err!=nil{return nil,err};defer rows.Close();items:=make([]%s,0);for rows.Next(){var v %s;if err:=rows.Scan(%s);err!=nil{return nil,err};items=append(items,v)};if err:=rows.Err();err!=nil{return nil,err};return items,nil}\n", n, n, n, fmt.Sprintf("SELECT %s, created_at, updated_at FROM %s ORDER BY id LIMIT $1 OFFSET $2", strings.Join(cols, ", "), d.Plural), n, n, scanArgs(d, "v"))
	sets := []string{}
	for i, f := range create {
		sets = append(sets, fmt.Sprintf("%s = $%d", f.Name, i+2))
	}
	fmt.Fprintf(&b, "func(q *Queries)Update%s(ctx context.Context,arg Update%sParams)(%s,error){row:=q.db.QueryRow(ctx,%q,arg.ID", n, n, n, fmt.Sprintf("UPDATE %s SET %s, updated_at = NOW() WHERE id = $1 RETURNING %s, created_at, updated_at", d.Plural, strings.Join(sets, ", "), strings.Join(cols, ", ")))
	for _, f := range create {
		fmt.Fprintf(&b, ",arg.%s", exported(f.Name))
	}
	fmt.Fprintf(&b, ");var v %s;err:=row.Scan(%s);return v,err}\n", n, scanArgs(d, "v"))
	fmt.Fprintf(&b, "func(q *Queries)Delete%s(ctx context.Context,id %s)(%s,error){row:=q.db.QueryRow(ctx,%q,id);var deleted %s;err:=row.Scan(&deleted);return deleted,err}\n", n, goType(d.ID().Type), goType(d.ID().Type), fmt.Sprintf("DELETE FROM %s WHERE id = $1 RETURNING id", d.Plural), goType(d.ID().Type))
	return b.String()
}

