func renderManagedResources(config project.Config, resources []resource.Definition) ([]Artifact, error) {
	if !config.OpenAPI.Enabled {
		return nil, nil
	}
	values := append([]resource.Definition(nil), resources...)
	sort.Slice(values, func(i, j int) bool { return values[i].Name < values[j].Name })
	registry, err := resource.Encode(values)
	if err != nil {
		return nil, err
	}
	spec := buildOpenAPI(config, values)
	artifacts := []Artifact{
		mustArtifact(resource.RegistryPath, registry, OwnershipGenerated),
		mustArtifact("api/openapi.yaml", []byte(spec), OwnershipGenerated),
		mustArtifact("internal/generated/openapi/spec.gen.go", mustFormat("internal/generated/openapi/spec.gen.go", buildSpecGo(config, spec)), OwnershipGenerated),
		mustArtifact("internal/bootstrap/resources.gen.go", mustFormat("internal/bootstrap/resources.gen.go", buildBootstrapResources(config, values)), OwnershipGenerated),
	}
	for _, definition := range values {
		if definition.Name == "order" {
			continue
		}
		generated, err := buildResourceArtifacts(config, definition, definition.Migration)
		if err != nil {
			return nil, err
		}
		artifacts = append(artifacts, generated...)
	}
	return artifacts, nil
}

func mustArtifact(path string, content []byte, ownership Ownership) Artifact {
	return Artifact{Path: path, Content: append([]byte(nil), content...), Mode: 0o644, Ownership: ownership}
}

func mustFormat(path, source string) []byte {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		panic(fmt.Sprintf("format %s: %v\n%s", path, err, source))
	}
	return formatted
}

func buildSpecGo(config project.Config, spec string) string {
	return fmt.Sprintf(`// Code generated by gosvc. DO NOT EDIT.
package openapi

import "github.com/getkin/kin-openapi/openapi3"

const rawSpec = %q
func RawSpec() []byte { return []byte(rawSpec) }
func GetSwagger() (*openapi3.T, error) { return openapi3.NewLoader().LoadFromData([]byte(rawSpec)) }
`, spec)
}

func buildBootstrapResources(config project.Config, resources []resource.Definition) string {
	var b strings.Builder
	b.WriteString("// Code generated by gosvc. DO NOT EDIT.\npackage bootstrap\n\nimport (\n")
	if config.API.Router == "echo" {
		b.WriteString("\t\"github.com/labstack/echo/v4\"\n\n")
	} else {
		b.WriteString("\t\"github.com/go-chi/chi/v5\"\n")
	}
	if config.Database.CodeGeneration == "sqlc" {
		b.WriteString("\t\"github.com/jackc/pgx/v5/pgxpool\"\n\n")
	}
	fmt.Fprintf(&b, "\t\"%s/internal/application\"\n", config.Project.Module)
	fmt.Fprintf(&b, "\thttpserver \"%s/internal/infrastructure/http\"\n", config.Project.Module)
	fmt.Fprintf(&b, "\t\"%s/internal/infrastructure/persistence/postgres\"\n", config.Project.Module)
	b.WriteString(")\n\n")
	if config.Database.CodeGeneration == "gorm" {
		b.WriteString("func buildAPIRoutes(pool *postgres.Pool) httpserver.RouteRegistrar {\n")
	} else {
		b.WriteString("func buildAPIRoutes(pool *pgxpool.Pool) httpserver.RouteRegistrar {\n")
	}
	for _, d := range resources {
		n := exported(d.Name)
		fmt.Fprintf(&b, "\t%sRepository := postgres.New%sRepository(pool)\n", d.Name, n)
		fmt.Fprintf(&b, "\t%sService := application.New%sService(%sRepository)\n", d.Name, n, d.Name)
		fmt.Fprintf(&b, "\t%sHandler := httpserver.New%sHandler(%sService)\n", d.Name, n, d.Name)
	}
	if config.API.Router == "echo" {
		b.WriteString("\treturn func(router *echo.Group) {\n")
	} else {
		b.WriteString("\treturn func(router chi.Router) {\n")
	}
	for _, d := range resources {
		fmt.Fprintf(&b, "\t\t%sHandler.RegisterRoutes(router)\n", d.Name)
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}

func buildResourceArtifacts(config project.Config, d resource.Definition, migration int) ([]Artifact, error) {
	builders := []struct {
		path, source string
		ownership    Ownership
	}{
		{fmt.Sprintf("internal/domain/%s.go", d.Name), buildDomain(d), OwnershipUser},
		{fmt.Sprintf("internal/domain/%s_errors.go", d.Name), buildErrors(d), OwnershipUser},
		{fmt.Sprintf("internal/ports/%s_repository.go", d.Name), buildPort(config, d), OwnershipUser},
		{fmt.Sprintf("internal/application/%s_service.go", d.Name), buildService(config, d), OwnershipUser},
		{fmt.Sprintf("internal/application/%s_service_test.go", d.Name), buildServiceTest(config, d), OwnershipUser},
		{fmt.Sprintf("db/migrations/%06d_create_%s.up.sql", migration, d.Plural), buildMigrationUp(d), OwnershipUser},
		{fmt.Sprintf("db/migrations/%06d_create_%s.down.sql", migration, d.Plural), fmt.Sprintf("DROP TABLE IF EXISTS %s;\n", d.Plural), OwnershipUser},
	}
	if config.Database.CodeGeneration == "gorm" {
		builders = append(builders,
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/persistence/postgres/%s_repository.go", d.Name), buildGORMRepository(config, d), OwnershipUser},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("tests/integration/%s_repository_test.go", d.Name), buildIntegrationTest(config, d), OwnershipUser},
		)
	} else {
		builders = append(builders,
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/persistence/postgres/%s_repository.go", d.Name), buildRepository(config, d), OwnershipUser},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/generated/sqlc/%s.sql.go", d.Plural), buildDBGen(d), OwnershipGenerated},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("db/queries/%s.sql", d.Plural), buildQueries(d), OwnershipUser},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("tests/integration/%s_repository_test.go", d.Name), buildIntegrationTest(config, d), OwnershipUser},
		)
	}
	if config.API.Router == "echo" {
		builders = append(builders,
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/http/%s_handler.go", d.Name), buildEchoHandler(config, d), OwnershipUser},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/http/%s_handler_test.go", d.Name), buildEchoHandlerTest(config, d), OwnershipUser},
		)
	} else {
		builders = append(builders,
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/http/%s_handler.go", d.Name), buildHandler(config, d), OwnershipUser},
			struct {
				path, source string
				ownership    Ownership
			}{fmt.Sprintf("internal/infrastructure/http/%s_handler_test.go", d.Name), buildHandlerTest(config, d), OwnershipUser},
		)
	}
	result := make([]Artifact, 0, len(builders))
	for _, item := range builders {
		content := []byte(item.source)
		if strings.HasSuffix(item.path, ".go") {
			f, err := format.Source(content)
			if err != nil {
				return nil, fmt.Errorf("format generated resource file %s: %w\n%s", item.path, err, content)
			}
			content = f
		}
		result = append(result, mustArtifact(item.path, content, item.ownership))
	}
	return result, nil
}

func buildDomain(d resource.Definition) string {
	var b strings.Builder
	b.WriteString("package domain\n\nimport (\n\t\"time\"\n")
	if hasFieldType(d, "uuid") {
		b.WriteString("\n\t\"github.com/google/uuid\"\n")
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(&b, "type %s struct {\n", exported(d.Name))
	for _, f := range d.Fields {
		fmt.Fprintf(&b, "\t%s %s\n", exported(f.Name), goType(f.Type))
	}
	b.WriteString("\tCreatedAt time.Time\n\tUpdatedAt time.Time\n}\n")
	return b.String()
}

