func sampleJSONPayload(d resource.Definition) string {
	parts := make([]string, 0)
	for index, field := range createFields(d) {
		var value string
		switch field.Type {
		case "uuid":
			value = fmt.Sprintf("\"00000000-0000-0000-0000-%012d\"", index+1)
		case "int64":
			value = fmt.Sprintf("%d", (index+1)*100)
		case "bool":
			value = "true"
		case "datetime":
			value = "\"2026-01-01T00:00:00Z\""
		default:
			value = fmt.Sprintf("%q", field.Name+"-sample")
		}
		parts = append(parts, fmt.Sprintf("%q:%s", field.Name, value))
	}
	return "{" + strings.Join(parts, ",") + "}"
}

func sampleDomainValue(d resource.Definition, withID bool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "domain.%s{", exported(d.Name))
	for index, field := range d.Fields {
		if field.Name == "id" && !withID {
			continue
		}
		value := sampleGoValue(field, index)
		fmt.Fprintf(&b, "%s:%s,", exported(field.Name), value)
	}
	b.WriteString("}")
	return b.String()
}

func sampleGoValue(field resource.Field, index int) string {
	switch field.Type {
	case "uuid":
		return fmt.Sprintf("uuid.UUID{%d}", index+1)
	case "int64":
		return fmt.Sprintf("%d", (index+1)*100)
	case "bool":
		return "true"
	case "datetime":
		return fmt.Sprintf("time.Unix(%d,0).UTC()", index+1)
	default:
		return fmt.Sprintf("%q", field.Name+"-sample")
	}
}
