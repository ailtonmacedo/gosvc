func TestRunAppliesPluginAtomicallyAndPreservesItDuringRegeneration(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("shell fixture")
	}
	projectDir, config := generatedProject(t)
	writePlugin(t, projectDir, "audit", `#!/bin/sh
read request
case "$GOSVC_PLUGIN_ACTION" in
  validate) printf '%s\n' '{"protocol_version":1,"diagnostics":[{"severity":"info","message":"audit is valid"}]}' ;;
  contribute) printf '%s\n' '{"protocol_version":1,"contribution":{"features":["trail"],"artifacts":[{"path":"internal/audit/audit.gen.go","content":"// Code generated by audit. DO NOT EDIT.\npackage audit\n","mode":420,"ownership":"generated"},{"path":"docs/AUDIT.md","content":"# Audit\n","mode":420,"ownership":"user"}]}}' ;;
esac
`)

	dryRun, err := Run(context.Background(), Options{ProjectDir: projectDir, PluginName: "audit", FrameworkVersion: "1.0.0", DryRun: true, Timeout: time.Second})
	if err != nil {
		t.Fatal(err)
	}
	if dryRun.Applied || dryRun.ManifestAction != generator.ActionUpdate {
		t.Fatalf("dry run = %+v", dryRun)
	}
	if _, err := os.Stat(filepath.Join(projectDir, "internal", "audit", "audit.gen.go")); !os.IsNotExist(err) {
		t.Fatalf("dry run wrote artifact: %v", err)
	}

	result, err := Run(context.Background(), Options{ProjectDir: projectDir, PluginName: "audit", FrameworkVersion: "1.0.0", Timeout: time.Second})
	if err != nil {
		t.Fatal(err)
	}
	if !result.Applied {
		t.Fatal("plugin was not applied")
	}
	value, err := manifest.Load(projectDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(value.Plugins) != 1 || value.Plugins[0].Name != "audit" || value.Plugins[0].Checksum == "" {
		t.Fatalf("plugins = %+v", value.Plugins)
	}
	if !contains(value.Features, "plugin:audit:trail") {
		t.Fatalf("features = %v", value.Features)
	}
	record, ok := value.File("internal/audit/audit.gen.go")
	if !ok || record.Producer != "audit" || record.Ownership != "generated" {
		t.Fatalf("plugin record = %+v, %v", record, ok)
	}

	second, err := Run(context.Background(), Options{ProjectDir: projectDir, PluginName: "audit", FrameworkVersion: "1.0.0", Timeout: time.Second})
	if err != nil {
		t.Fatal(err)
	}
	if second.Applied {
		t.Fatal("second plugin run was not idempotent")
	}

	regenerated, err := generator.Generate(generator.Request{Config: config, Destination: projectDir, FrameworkVersion: "1.0.0"})
	if err != nil {
		t.Fatal(err)
	}
	if regenerated.Applied {
		t.Fatal("unchanged core regeneration should not apply")
	}
	value, err = manifest.Load(projectDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(value.Plugins) != 1 || !contains(value.Features, "plugin:audit:trail") {
		t.Fatalf("plugin metadata lost after regeneration: %+v", value)
	}
}

